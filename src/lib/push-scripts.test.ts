/**
 * The sidecar's arms, run as the REAL generated bytes against a real socket,
 * exactly as lib/hook-scripts.test.ts runs the two older hooks and for the same
 * reason: these files ship into a harness's settings.json, never go through the
 * bundler, and their whole contract is process behavior — what lands on stdout,
 * what reaches the wire, and what does not.
 *
 * The two facts every case here turns on: the team shelf is searched first and a
 * hit there makes NO request, and the research arm is the only arm that may deny
 * a tool call.
 */

let dataDir: string;
let scriptDir: string;
let server: Server | null = null;

beforeEach(async () => {
  dataDir = await mkdtemp(join(tmpdir(), 'tenjin-push-data-'));
  scriptDir = await mkdtemp(join(tmpdir(), 'tenjin-push-bin-'));
});

afterEach(async () => {
  if (server !== null) await new Promise<void>((res) => server!.close(() => res()));
  server = null;
  await rm(dataDir, { recursive: true, force: true });
  await rm(scriptDir, { recursive: true, force: true });
});

interface HookRun {
  code: number | null;
  stdout: string;
  stderr: string;
}

async function runScript(source: string, stdin: string): Promise<HookRun> {
  const path = join(scriptDir, `hook-${Math.random().toString(36).slice(2)}.mjs`);
  await writeFile(path, source, { mode: 0o755 });
  return await new Promise<HookRun>((resolve, reject) => {
    const child = spawn(process.execPath, [path], {
      stdio: ['pipe', 'pipe', 'pipe'],
      env: { PATH: process.env.PATH ?? '' },
    });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (c) => (stdout += String(c)));
    child.stderr.on('data', (c) => (stderr += String(c)));
    child.on('error', reject);
    child.on('close', (code) => resolve({ code, stdout, stderr }));
    child.stdin.end(stdin);
  });
}

interface StubRequest {
  url: string;
  body: string;
  base: string;
}

/** The marketplace, and the free-body endpoint a candidate url points at. */
async function serve(
  handler: (req: StubRequest) => { status: number; json: unknown; delayMs?: number } | 'hang',
): Promise<{
  baseUrl: string;
  hits: () => number;
  /** The `query` field of every search request that reached the wire. */
  queries: () => string[];
}> {
  let hits = 0;
  let base = '';
  const queries: string[] = [];
  const s = createServer((req: IncomingMessage, res) => {
    hits += 1;
    let body = '';
    req.on('data', (c) => (body += String(c)));
    req.on('end', () => {
      const url = req.url ?? '';
      if (url.startsWith('/api/search')) {
        try {
          queries.push(String((JSON.parse(body) as { query?: unknown }).query));
        } catch {
          queries.push('');
        }
      }
      const out = handler({ url, body, base });
      if (out === 'hang') return;
      const answer = (): void => {
        res.writeHead(out.status, { 'content-type': 'application/json' });
        res.end(JSON.stringify(out.json));
      };
      if (out.delayMs === undefined) answer();
      else setTimeout(answer, out.delayMs).unref();
    });
  });
  server = s;
  await new Promise<void>((res) => s.listen(0, '127.0.0.1', () => res()));
  const addr = s.address();
  const port = typeof addr === 'object' && addr !== null ? addr.port : 0;
  base = `http://127.0.0.1:${port}`;
  return { baseUrl: base, hits: () => hits, queries: () => queries };
}

const SEARCH_ID = '22222222-2222-4222-8222-222222222222';
const RESOURCE_ID = '11111111-1111-4111-8111-111111111111';
/** Rank 2: what a margin is measured against. */
const SECOND_RESOURCE_ID = '33333333-3333-4333-8333-333333333333';
const BODY_MD = 'Pin the resolver to 4.1 and the parse stops throwing. Verified 2026-08-20.';
const SESSION = 'sess-1';

/**
 * A marketplace that answers with a candidate whose title is the query it was
 * asked. That makes the overlap score 1.0, which is what puts every case that
 * wants a strong hit on the strong path without hand-tuning words; a case that
 * wants a weak one passes its own title.
 *
 * A SECOND, UNRELATED CANDIDATE RIDES ALONG, because 'strong' now requires a
 * rank 2 to have beaten: with one piece back the margin test compares against
 * zero and proves nothing, so a lone piece is at most 'moderate'. This filler
 * shares no content word with any query here, so the margin is the whole score.
 */
const echo =
  (over: Record<string, unknown> = {}) =>
  (req: StubRequest): { status: number; json: unknown } => {
    if (req.url.startsWith('/api/search')) {
      let query: string;
      try {
        query = String((JSON.parse(req.body) as { query?: unknown }).query);
      } catch {
        query = '';
      }
      return {
        status: 200,
        json: {
          schemaVersion: 3,
          searchId: SEARCH_ID,
          items: [
            {
              resourceId: RESOURCE_ID,
              url: `${req.base}/@a/p`,
              title: query.slice(0, 190),
              price: '0',
              excerpt: 'the excerpt',
              creator: { handle: 'vraspar' },
              ...over,
            },
            {
              resourceId: SECOND_RESOURCE_ID,
              url: `${req.base}/@b/q`,
              title: 'unrelated pgvector snapshot slot',
              price: '0',
              excerpt: 'about something else entirely',
              creator: { handle: 'someone' },
            },
          ],
        },
      };
    }
    return { status: 200, json: { bodyMd: BODY_MD } };
  };

const miss = (req: StubRequest): { status: number; json: unknown } =>
  req.url.startsWith('/api/search')
    ? { status: 200, json: { schemaVersion: 3, searchId: SEARCH_ID, items: [] } }
    : { status: 404, json: {} };

async function writeConfig(config: Record<string, unknown>): Promise<void> {
  await writeFile(join(dataDir, 'config.json'), JSON.stringify(config, null, 2));
}

/** Push on, pointed at the stub. */
async function pushOn(baseUrl: string, hooks: Record<string, unknown> = {}): Promise<void> {
  await writeConfig({ baseUrl, hooks: { push: 'on', ...hooks } });
}

/** A note on the team shelf, in the format lib/notes.ts writes. */
async function writeNote(id: string, question: string, body: string): Promise<void> {
  const dir = join(dataDir, 'notes', 'notes');
  await mkdir(dir, { recursive: true });
  await writeFile(
    join(dir, `${id}.md`),
    [
      '---',
      `question: "${question}"`,
      'applies_to: [tenjin, drizzle]',
      'scope: "local dev"',
      'as_of: 2026-08-22',
      'author: vraspar',
      'source: ""',
      'visibility: team',
      '---',
      body,
      '',
    ].join('\n'),
  );
}

interface LedgerRow {
  [key: string]: unknown;
  trigger?: string;
  shelf?: string;
  action?: string;
  form?: string;
  deny?: boolean;
  reason?: string;
  candidate?: { id?: string; resourceId?: string; title?: string } | null;
}

async function ledger(): Promise<LedgerRow[]> {
  const path = join(dataDir, PUSH_LEDGER_FILE);
  if (!existsSync(path)) return [];
  const text = await readFile(path, 'utf8');
  return text
    .split('\n')
    .filter((line) => line.length > 0)
    .map((line) => JSON.parse(line) as LedgerRow);
}

/** The additionalContext a run injected, or null when it stayed silent. */
function injected(run: HookRun): string | null {
  if (run.stdout.trim().length === 0) return null;
  const parsed = JSON.parse(run.stdout) as {
    hookSpecificOutput?: { additionalContext?: string };
  };
  return parsed.hookSpecificOutput?.additionalContext ?? null;
}

/** The reason a run denied the tool call with, or null when it did not deny. */
function denied(run: HookRun): string | null {
  if (run.stdout.trim().length === 0) return null;
  const parsed = JSON.parse(run.stdout) as {
    hookSpecificOutput?: { permissionDecision?: string; permissionDecisionReason?: string };
  };
  if (parsed.hookSpecificOutput?.permissionDecision !== 'deny') return null;
  return parsed.hookSpecificOutput.permissionDecisionReason ?? null;
}

