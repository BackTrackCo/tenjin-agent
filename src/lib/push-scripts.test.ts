describe('the prompt arm (UserPromptSubmit)', () => {
  const prompt = (text: string): string =>
    JSON.stringify({ session_id: SESSION, hook_event_name: 'UserPromptSubmit', prompt: text });

  const QUESTION =
    'The zod resolver throws on an optional chain during parse and I need to know whether pinning helps';

  it('injects on the same turn, and scrubs the paths out of what it sends', async () => {
    const { baseUrl, queries } = await serve(echo());
    await pushOn(baseUrl);

    const run = await runScript(
      pushPromptHookScript(dataDir),
      prompt(`${QUESTION} in /Users/vraspar/work/app/src/thing.ts`),
    );
    expect(run.code).toBe(0);
    expect(injected(run)).toContain(BODY_MD);
    expect(queries()[0]).not.toContain('/Users/vraspar');
    expect((await ledger())[0]).toMatchObject({
      trigger: 'prompt',
      event: 'UserPromptSubmit',
      action: 'injected',
      // The prompt arm cannot deny: there is no tool call to deny.
      deny: false,
    });
  });

  it('skips a short prompt and a slash command without asking anything', async () => {
    const { baseUrl, hits } = await serve(echo());
    await pushOn(baseUrl);

    const short = await runScript(pushPromptHookScript(dataDir), prompt('yes, do that'));
    expect(short.stdout).toBe('');
    const slash = await runScript(pushPromptHookScript(dataDir), prompt(`/review ${QUESTION}`));
    expect(slash.stdout).toBe('');
    expect(hits()).toBe(0);
    expect(await ledger()).toEqual([]);
  });

  it('reads the older user_input spelling too', async () => {
    const { baseUrl } = await serve(echo());
    await pushOn(baseUrl);
    const run = await runScript(
      pushPromptHookScript(dataDir),
      JSON.stringify({
        session_id: SESSION,
        hook_event_name: 'UserPromptSubmit',
        user_input: QUESTION,
      }),
    );
    expect(injected(run)).toContain(BODY_MD);
  });

  /**
   * The invariant behind the case below, pinned as arithmetic because the way it
   * broke was arithmetic: someone tightened the watchdog without looking at what
   * the arm spends under it, and the whole cost of a lookup was paid for an
   * injection that was killed before it could happen.
   */
  it('cannot start more work than its watchdog allows', () => {
    expect(PUSH_PROMPT_SEARCH_TIMEOUT_MS + PUSH_PROMPT_BODY_TIMEOUT_MS).toBeLessThan(
      PUSH_PROMPT_BUDGET_MS,
    );
    expect(PUSH_PROMPT_BUDGET_MS).toBeLessThan(PUSH_PROMPT_WATCHDOG_MS);
  });

  /**
   * The arm sits between a keypress and the first token, so its watchdog has to
   * be bigger than the work it starts. It was not: search (1500) plus body
   * (1500) overran a 2500ms kill, and a killed run injected nothing AND wrote no
   * ledger row, while the search it had already paid for sat in searches.json.
   */
  it('gives up on a slow body rather than being killed holding one', async () => {
    const slow = echo();
    const { baseUrl } = await serve((req) => ({ ...slow(req), delayMs: 1200 }));
    await pushOn(baseUrl);

    const run = await runScript(pushPromptHookScript(dataDir), prompt(QUESTION));
    expect(run.code).toBe(0);
    // The search fitted, the body did not: the pointer is what it says.
    const text = injected(run);
    expect(text).toContain('Read it free: tenjin read');
    expect(text).not.toContain(BODY_MD);
    const rows = await ledger();
    expect(rows).toHaveLength(1);
    expect(rows[0]).toMatchObject({ trigger: 'prompt', action: 'injected', form: 'short' });
  });

  /** A run that overruns anyway is visible: the ledger is what `push status`
   *  tunes the thresholds from, so a silent death is the one outcome it cannot
   *  afford. */
  it('records the overrun when the marketplace never answers at all', async () => {
    const { baseUrl } = await serve(() => 'hang');
    await pushOn(baseUrl);
    const run = await runScript(pushPromptHookScript(dataDir), prompt(QUESTION));
    expect(run.code).toBe(0);
    expect(run.stdout).toBe('');
    const rows = await ledger();
    expect(rows).toHaveLength(1);
    expect(['no-answer', 'watchdog']).toContain(rows[0]!.reason);
  });

  it('stays silent when the marketplace never answers', async () => {
    const { baseUrl } = await serve(() => 'hang');
    await pushOn(baseUrl);
    const run = await runScript(pushPromptHookScript(dataDir), prompt(QUESTION));
    expect(run.code).toBe(0);
    expect(run.stdout).toBe('');
    expect(run.stderr).toBe('');
    expect((await ledger())[0]).toMatchObject({ action: 'skipped', reason: 'no-answer' });
  });

  /**
   * An unanswered lookup used to be free: pushBudget counted rows carrying a
   * searchId, and an outage writes rows that carry none. So a session could ask
   * a dead marketplace forever, paying the fetch timeout in front of every turn.
   */
  it('stops asking a marketplace that is not answering', async () => {
    // Nothing is listening here; every attempt fails at once.
    await writeConfig({ baseUrl: 'http://127.0.0.1:1', hooks: { push: 'on' } });
    const asks = [
      'The zod resolver throws on an optional chain during parse and I want to know if pinning helps',
      'The drizzle snapshot check passes but the next generate breaks, is the hand patch the cause here',
      'The pgvector testcontainer flips its collation when the image is swapped, does the seed order matter',
    ];
    for (const ask of asks) {
      const run = await runScript(pushPromptHookScript(dataDir), prompt(ask));
      expect(run.code).toBe(0);
      expect(run.stdout).toBe('');
    }
    const rows = await ledger();
    expect(rows.map((r) => r.reason)).toEqual(['no-answer', 'no-answer', 'quiet']);
  });

  it('does nothing at all with push off', async () => {
    const { baseUrl, hits } = await serve(echo());
    await writeConfig({ baseUrl });
    const run = await runScript(pushPromptHookScript(dataDir), prompt(QUESTION));
    expect(run.stdout).toBe('');
    expect(hits()).toBe(0);
  });
});

describe('the failure arm (PostToolUse Bash)', () => {
  const failure = (): string =>
    JSON.stringify({
      session_id: SESSION,
      hook_event_name: 'PostToolUse',
      tool_name: 'Bash',
      tool_input: { command: 'pnpm install left-pad' },
      tool_response: {
        stdout: '',
        stderr: "Error: Cannot find module 'left-pad' required by the vitest resolver",
        exit_code: 1,
        interrupted: false,
      },
    });

  it('names the package the failure was about, then never asks twice', async () => {
    const { baseUrl, hits, queries } = await serve(echo());
    await pushOn(baseUrl);

    const first = await runScript(pushFailureHookScript(dataDir), failure());
    expect(injected(first)).toContain(BODY_MD);
    expect(queries()[0]).toContain('left-pad');
    const askedOnce = hits();

    // The same command re-run is the same problem. Both PostToolUse and
    // PostToolUseFailure can fire for one failure, too.
    const second = await runScript(pushFailureHookScript(dataDir), failure());
    expect(second.stdout).toBe('');
    expect(hits()).toBe(askedOnce);
    expect(await ledger()).toHaveLength(1);
  });

  it('reads the top-level error string of a PostToolUseFailure', async () => {
    const { baseUrl, queries } = await serve(echo());
    await pushOn(baseUrl);
    const run = await runScript(
      pushFailureHookScript(dataDir),
      JSON.stringify({
        session_id: SESSION,
        hook_event_name: 'PostToolUseFailure',
        tool_name: 'Bash',
        tool_input: { command: 'pnpm test' },
        error: "Exit code 1\nTypeError: Cannot find module 'left-pad' from the vitest resolver",
      }),
    );
    expect(queries()[0]).toContain('left-pad');
    expect((await ledger())[0]).toMatchObject({
      trigger: 'failure',
      event: 'PostToolUseFailure',
      action: 'injected',
    });
    expect(injected(run)).toContain(BODY_MD);
  });

  /**
   * The REAL Bash tool_response shape: {stdout, stderr, interrupted, isImage},
   * with no exit_code at all, and a runner that printed its failure to stdout.
   * Reading only stderr when the code is unknown made the whole arm dead on the
   * harness it ships against.
   */
  it('reads a failure the runner printed to stdout with no exit code', async () => {
    const { baseUrl, queries } = await serve(echo());
    await pushOn(baseUrl);
    const run = await runScript(
      pushFailureHookScript(dataDir),
      JSON.stringify({
        session_id: SESSION,
        hook_event_name: 'PostToolUse',
        tool_name: 'Bash',
        tool_input: { command: 'pnpm vitest run' },
        tool_response: {
          stdout: "FAIL src/x.test.ts\nTypeError: Cannot find module 'left-pad' from the resolver",
          stderr: '',
          interrupted: false,
          isImage: false,
        },
      }),
    );
    expect(run.code).toBe(0);
    expect(queries()[0] ?? '').toContain('left-pad');
    expect((await ledger())[0]).toMatchObject({ trigger: 'failure', action: 'injected' });
  });

  it('stays out of the way of a command that printed nothing wrong', async () => {
    const { baseUrl, hits } = await serve(echo());
    await pushOn(baseUrl);
    const run = await runScript(
      pushFailureHookScript(dataDir),
      JSON.stringify({
        session_id: SESSION,
        hook_event_name: 'PostToolUse',
        tool_name: 'Bash',
        tool_input: { command: 'pnpm vitest run' },
        tool_response: { stdout: 'Tests  204 passed (204)', stderr: '', interrupted: false },
      }),
    );
    expect(run.stdout).toBe('');
    expect(hits()).toBe(0);
    expect(await ledger()).toEqual([]);
  });

  /**
   * An auth failure is the failure this arm fires on most often, so the token in
   * it is the common case and not the edge. Nothing credential-shaped may reach
   * the wire, and nothing credential-shaped may reach the ledger either: the
   * ledger row carries the same string the request did.
   */
  it('strips the credential out of an auth failure before it leaves the machine', async () => {
    const { baseUrl, queries } = await serve(echo());
    await pushOn(baseUrl);
    const run = await runScript(
      pushFailureHookScript(dataDir),
      JSON.stringify({
        session_id: SESSION,
        hook_event_name: 'PostToolUseFailure',
        tool_name: 'Bash',
        tool_input: { command: 'git push origin main' },
        error:
          'fatal: Authentication failed for token ghp_16C7e42F292c6912E7710c838347Ae178B4a using account vraspar-ops',
      }),
    );
    expect(run.code).toBe(0);
    const sent = queries()[0] ?? '';
    expect(sent).toContain('Authentication');
    expect(sent).not.toContain('ghp_');
    expect(sent).not.toContain('16C7e42F292c6912E7710c838347Ae178B4a');
    const rows = await ledger();
    expect(String(rows[0]!.query)).not.toContain('ghp_');
  });
});

