/** One `session_state` value, parsed. Null when the key was never written. */
function sessionState(session: string, key: string): unknown {
  const path = join(dataDir, STATE_DB_FILE);
  if (!existsSync(path)) return null;
  const db = new DatabaseSync(path);
  try {
    const row = db
      .prepare('SELECT value FROM session_state WHERE session = ? AND key = ?')
      .get(session, key) as unknown as { value?: string } | undefined;
    return row?.value === undefined ? null : JSON.parse(row.value);
  } finally {
    db.close();
  }
}

/** The additionalContext a run injected, or null when it stayed silent. */
function injected(run: HookRun): string | null {
  if (run.stdout.trim().length === 0) return null;
  const parsed = JSON.parse(run.stdout) as {
    hookSpecificOutput?: { additionalContext?: string };
  };
  return parsed.hookSpecificOutput?.additionalContext ?? null;
}

/** The reason a run denied the tool call with, or null when it did not deny. */
function denied(run: HookRun): string | null {
  if (run.stdout.trim().length === 0) return null;
  const parsed = JSON.parse(run.stdout) as {
    hookSpecificOutput?: { permissionDecision?: string; permissionDecisionReason?: string };
  };
  if (parsed.hookSpecificOutput?.permissionDecision !== 'deny') return null;
  return parsed.hookSpecificOutput.permissionDecisionReason ?? null;
}

