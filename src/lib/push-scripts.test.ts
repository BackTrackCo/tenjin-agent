describe('the capture ask (Stop)', () => {
  const stopInput = JSON.stringify({ session_id: SESSION, hook_event_name: 'Stop', cwd: '/tmp' });

  /** A recorded search stamped with this session: the research signal. */
  async function writeSearchSignal(): Promise<void> {
    await writeFile(
      join(dataDir, 'searches.json'),
      JSON.stringify({
        schemaVersion: 1,
        searches: [
          {
            searchId: SEARCH_ID,
            at: new Date().toISOString(),
            question: 'zod parse',
            decision: 'CANDIDATES',
            candidates: [],
            source: 'cli',
            sessionId: SESSION,
          },
        ],
      }),
    );
  }

  it('blocks once, with nothing else on stdout, then lets the session end', async () => {
    await writeConfig({ hooks: { capture: 'block' } });
    await writeSearchSignal();

    const first = await runScript(stopHookScript(dataDir), stopInput);
    expect(first.code).toBe(0);
    expect(JSON.parse(first.stdout)).toEqual({ decision: 'block', reason: CAPTURE_REASON });
    // The marker `notes add` / `notes none` reads to learn which session to clear.
    expect(await readFile(join(dataDir, 'push', 'capture-pending'), 'utf8')).toBe(SESSION);

    const second = await runScript(stopHookScript(dataDir), stopInput);
    expect(second.stdout).toBe('');
  });

  it('takes an injected push-ledger row as the research signal too', async () => {
    await writeConfig({ hooks: { capture: 'block' } });
    await mkdir(dataDir, { recursive: true });
    await writeFile(
      join(dataDir, PUSH_LEDGER_FILE),
      `${JSON.stringify({ at: new Date().toISOString(), session: SESSION, trigger: 'prompt', action: 'injected' })}\n`,
    );
    const run = await runScript(stopHookScript(dataDir), stopInput);
    expect(JSON.parse(run.stdout)).toEqual({ decision: 'block', reason: CAPTURE_REASON });
  });

  /**
   * The sidecar's own telemetry is not the session's research. The log-only read
   * arm fires on the first source file the agent opens and writes both a
   * push-hook search and a ledger row, which used to mean nearly every push-on
   * session ended in a block — including one that only read and edited code.
   */
  it('is not fooled by the sidecar looking things up on its own', async () => {
    await writeConfig({ hooks: { capture: 'block' } });
    await mkdir(dataDir, { recursive: true });
    await writeFile(
      join(dataDir, PUSH_LEDGER_FILE),
      [
        JSON.stringify({
          at: new Date().toISOString(),
          session: SESSION,
          trigger: 'read',
          action: 'logged',
        }),
        JSON.stringify({
          at: new Date().toISOString(),
          session: SESSION,
          trigger: 'prompt',
          action: 'skipped',
          reason: 'miss',
        }),
        '',
      ].join('\n'),
    );
    await writeFile(
      join(dataDir, 'searches.json'),
      JSON.stringify({
        schemaVersion: 1,
        searches: [
          {
            searchId: SEARCH_ID,
            at: new Date().toISOString(),
            question: 'zod gotcha bug workaround',
            decision: 'MISS',
            candidates: [],
            source: 'push-hook',
            sessionId: SESSION,
          },
        ],
      }),
    );
    const run = await runScript(stopHookScript(dataDir), stopInput);
    expect(run.stdout).toBe('');
  });

  it('says the same thing as context under nudge, and blocks nothing', async () => {
    await writeConfig({ hooks: { capture: 'nudge' } });
    await writeSearchSignal();
    const run = await runScript(stopHookScript(dataDir), stopInput);
    expect(run.stdout).not.toContain('"decision"');
    expect(injected(run)).toBe(CAPTURE_REASON);
  });

  it('asks nothing of a session that did no research, or with capture off', async () => {
    await writeConfig({ hooks: { capture: 'block' } });
    const quiet = await runScript(stopHookScript(dataDir), stopInput);
    expect(quiet.stdout).toBe('');

    await writeConfig({});
    await writeSearchSignal();
    const off = await runScript(stopHookScript(dataDir), stopInput);
    expect(off.stdout).toBe('');
  });
});
