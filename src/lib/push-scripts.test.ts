describe('the state store the CLI and the scripts each carry', () => {
  /**
   * The generated scripts bake their own copy of the path, so a rename in
   * lib/state-store.ts that missed one of them would leave a sidecar writing to
   * a database the CLI never reads — silently, because every reader of it fails
   * closed to empty.
   */
  it('is one filename, and the generated core resolves it from DATA_DIR', () => {
    expect(STATE_DB_FILE).toBe('state.db');
    for (const source of [
      pushPromptHookScript(dataDir),
      pushFailureHookScript(dataDir),
      pushSubagentHookScript(dataDir),
      pushContextHookScript(dataDir),
      stopHookScript(dataDir),
      sessionPrimerHookScript(dataDir),
      websearchHookScript(dataDir),
      dispatchHookScript(dataDir),
    ]) {
      expect(source).toContain(
        `const STATE_DB_PATH = join(DATA_DIR, ${JSON.stringify(STATE_DB_FILE)});`,
      );
    }
  });

  /** No generated script may name a retired file. */
  it('leaves no reader of the files the store replaced', () => {
    for (const source of [
      pushPromptHookScript(dataDir),
      pushFailureHookScript(dataDir),
      pushSubagentHookScript(dataDir),
      pushContextHookScript(dataDir),
      stopHookScript(dataDir),
      websearchHookScript(dataDir),
      dispatchHookScript(dataDir),
    ]) {
      // The PATHS, not the prose: several comments still explain what the store
      // replaced, and that history is worth keeping.
      expect(source).not.toContain("join(DATA_DIR, 'push-ledger.jsonl')");
      expect(source).not.toContain("join(DATA_DIR, 'searches.json')");
      expect(source).not.toContain("'capture-asked-'");
      expect(source).not.toContain('LEDGER_TAIL_BYTES');
    }
  });
});
