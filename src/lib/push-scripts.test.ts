interface LedgerRow {
  [key: string]: unknown;
  trigger?: string;
  shelf?: string;
  action?: string;
  form?: string;
  deny?: boolean;
  reason?: string;
  candidate?: { id?: string; resourceId?: string; title?: string } | null;
}

/**
 * The decision rows a run left behind, in the shape the ledger used to write.
 *
 * The rows live in `state.db` now (tenjin-agent#209), split across `events` (one
 * per fire, carrying the query and the harness event name) and `injections` (one
 * per decision). This projects the join back into the flat JSONL row the
 * assertions in this file are written against — deliberately, because those
 * assertions are about the sidecar's BEHAVIOUR, and rewriting a hundred of them
 * into column names would have made a storage change look like a behaviour
 * change in the diff.
 */
async function ledger(): Promise<LedgerRow[]> {
  const path = join(dataDir, STATE_DB_FILE);
  if (!existsSync(path)) return [];
  const db = new DatabaseSync(path);
  try {
    const rows = db
      .prepare(
        `SELECT i.*, e.data AS event_data FROM injections i
           LEFT JOIN events e ON e.uid = i.event_uid
         ORDER BY i.id`,
      )
      .all() as unknown as Record<string, unknown>[];
    return rows.map((r) => {
      const event = typeof r.event_data === 'string' ? JSON.parse(r.event_data) : {};
      return {
        at: new Date(Number(r.at)).toISOString(),
        session: r.session === '' ? null : r.session,
        trigger: r.hook as string,
        event: event.event,
        query: event.query,
        shelf: r.shelf as string,
        searchId: r.search_id ?? undefined,
        candidate:
          r.resource_id === null
            ? null
            : { resourceId: r.resource_id, title: r.title, price: r.price, url: r.url },
        score: r.score,
        second: r.second,
        strength: r.strength,
        confidence: r.confidence,
        corroborated: r.corroborated === null ? null : r.corroborated === 1,
        action: r.action as string,
        reason: r.reason ?? undefined,
        form: r.form ?? undefined,
        deny: r.deny === 1,
        tokens: r.tokens ?? undefined,
        agentType: event.agentType,
      } as LedgerRow;
    });
  } finally {
    db.close();
  }
}

interface EventRow {
  [key: string]: unknown;
  session: string;
  hook: string;
  tool: string | null;
  error_hash: string | null;
  files: string[];
  data: Record<string, unknown>;
}

/** Every event row a run wrote, oldest first, with the JSON columns parsed. */
async function events(): Promise<EventRow[]> {
  const path = join(dataDir, STATE_DB_FILE);
  if (!existsSync(path)) return [];
  const db = new DatabaseSync(path);
  try {
    return (
      db.prepare('SELECT * FROM events ORDER BY id').all() as unknown as Record<string, unknown>[]
    ).map(
      (r) =>
        ({
          ...r,
          files: typeof r.files === 'string' ? (JSON.parse(r.files) as string[]) : [],
          data: typeof r.data === 'string' ? (JSON.parse(r.data) as Record<string, unknown>) : {},
        }) as EventRow,
    );
  } finally {
    db.close();
  }
}

/** Every pairing row, oldest first, `error_files` parsed. */
async function pairings(): Promise<Array<Record<string, unknown> & { error_files: string[] }>> {
  const path = join(dataDir, STATE_DB_FILE);
  if (!existsSync(path)) return [];
  const db = new DatabaseSync(path);
  try {
    return (
      db.prepare('SELECT * FROM pairings ORDER BY id').all() as unknown as Record<string, unknown>[]
    ).map((r) => ({
      ...r,
      error_files: typeof r.error_files === 'string' ? (JSON.parse(r.error_files) as string[]) : [],
    }));
  } finally {
    db.close();
  }
}

