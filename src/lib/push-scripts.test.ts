/** A shelf that answers one query strongly and everything else with a miss. */
const answersOnly =
  (word: RegExp, resourceId: string, bodyMd: string) =>
  (req: StubRequest): { status: number; json: unknown } => {
    if (!req.url.startsWith('/api/search')) return { status: 200, json: { bodyMd } };
    let query: string;
    try {
      query = String((JSON.parse(req.body) as { query?: unknown }).query ?? '');
    } catch {
      query = '';
    }
    if (!word.test(query)) {
      return { status: 200, json: { schemaVersion: 3, searchId: SEARCH_ID, items: [] } };
    }
    return {
      status: 200,
      json: {
        schemaVersion: 3,
        searchId: SEARCH_ID,
        items: [
          {
            resourceId,
            url: `${req.base}/@a/p`,
            title: query.slice(0, 190),
            price: '0',
            excerpt: 'the excerpt',
            creator: { handle: 'vraspar' },
            confidence: 'high',
            corroborated: true,
          },
          {
            resourceId: SECOND_RESOURCE_ID,
            url: `${req.base}/@b/q`,
            title: 'unrelated pgvector snapshot slot',
            price: '0',
            excerpt: 'about something else entirely',
            creator: { handle: 'someone' },
          },
        ],
      },
    };
  };

/** Team mode: baseUrl is the team stub, publicShelfUrl is the other one. */
async function teamMode(team: Stub, pub: Stub, hooks: Record<string, unknown> = {}): Promise<void> {
  await writeConfig({
    baseUrl: team.baseUrl,
    publicShelfUrl: pub.baseUrl,
    shelfBypassSecret: SECRET,
    hooks: { push: 'on', ...hooks },
  });
}

