describe('the capture ask (Stop)', () => {
  const stopInput = JSON.stringify({ session_id: SESSION, hook_event_name: 'Stop', cwd: '/tmp' });

  /** The ask as the hook renders it: the mode is spliced into the text, because
   *  it is what decides whether the agent may run the command it was handed. */
  const publicAsk = CAPTURE_REASON.replace('<mode>', 'review');
  const teamAsk = CAPTURE_REASON_TEAM.replace('<mode>', 'review');

  /** A recorded search stamped with this session: the research signal. */
  async function writeSearchSignal(): Promise<void> {
    await writeFile(
      join(dataDir, 'searches.json'),
      JSON.stringify({
        schemaVersion: 1,
        searches: [
          {
            searchId: SEARCH_ID,
            at: new Date().toISOString(),
            question: 'zod parse',
            decision: 'CANDIDATES',
            candidates: [],
            source: 'cli',
            sessionId: SESSION,
          },
        ],
      }),
    );
  }

  it('blocks once, with nothing else on stdout, then lets the session end', async () => {
    await writeConfig({ hooks: { capture: 'block' } });
    await writeSearchSignal();

    const first = await runScript(stopHookScript(dataDir), stopInput);
    expect(first.code).toBe(0);
    expect(JSON.parse(first.stdout)).toEqual({ decision: 'block', reason: publicAsk });
    // Answered by publishing OR by stopping again, and the hook cannot tell the
    // two apart, so the marker alone is what makes the second stop silent.
    expect(existsSync(join(dataDir, 'push', `capture-asked-${SESSION}`))).toBe(true);

    const second = await runScript(stopHookScript(dataDir), stopInput);
    expect(second.stdout).toBe('');
  });

  it('uses the team criteria, and names the team shelf, when a bypass secret is set', async () => {
    await writeConfig({ shelfBypassSecret: SECRET, hooks: { capture: 'block' } });
    await writeSearchSignal();
    const run = await runScript(stopHookScript(dataDir), stopInput);
    expect(JSON.parse(run.stdout)).toEqual({ decision: 'block', reason: teamAsk });
    const reason = (JSON.parse(run.stdout) as { reason: string }).reason;
    expect(reason).toContain('a teammate on this project would want to know');
    expect(reason).toContain('publish it to the team shelf');
    // The public bar is not applied to a shelf that is not public.
    expect(reason).not.toContain('rights-clean');
  });

  it('names the resolved publish mode in the ask', async () => {
    await writeConfig({ publish: { mode: 'full-auto' }, hooks: { capture: 'block' } });
    await writeSearchSignal();
    const run = await runScript(stopHookScript(dataDir), stopInput);
    expect((JSON.parse(run.stdout) as { reason: string }).reason).toContain(
      'publish.mode is full-auto',
    );
  });

  /**
   * Both arms end a turn by saying "publish what you learned". With capture on,
   * the ask has already said it once with the exact command; the per-search
   * lines beside it are the third publish prompt on one turn end.
   */
  it('replaces the open-loop MISS nag rather than stacking on top of it', async () => {
    await writeFile(
      join(dataDir, 'searches.json'),
      JSON.stringify({
        schemaVersion: 1,
        searches: [
          {
            searchId: SEARCH_ID,
            at: new Date().toISOString(),
            question: 'a question nobody answered',
            decision: 'MISS',
            candidates: [],
            source: 'cli',
            sessionId: SESSION,
          },
        ],
      }),
    );
    // Capture off: the MISS nag is what a turn end says.
    await writeConfig({});
    const nagged = await runScript(stopHookScript(dataDir), stopInput);
    expect(injected(nagged)).toContain('Open Tenjin loop');

    // Capture on: the ask, and only the ask.
    await rm(join(dataDir, 'hook-nags.json'), { force: true });
    await writeConfig({ hooks: { capture: 'nudge' } });
    const asked = await runScript(stopHookScript(dataDir), stopInput);
    expect(injected(asked)).toBe(publicAsk);
    expect(injected(asked)).not.toContain('Open Tenjin loop');
  });

  /**
   * The one generated output with no fail-open floor under it. The ask is made
   * once because a marker records it, and the marker lives under the data dir.
   * If the marker cannot be written, an opted-in `block` blocks every turn end
   * forever and the operator cannot end the session.
   */
  it('degrades a block to a nudge when the marker cannot be written', async () => {
    await writeConfig({ hooks: { capture: 'block' } });
    await writeSearchSignal();
    // No push/ subdirectory yet, and the data dir it would go in is read-only.
    await chmod(dataDir, 0o500);
    try {
      const run = await runScript(stopHookScript(dataDir), stopInput);
      expect(run.code).toBe(0);
      // A nudge, not a block: the session can end.
      expect(run.stdout).not.toContain('"decision":"block"');
      expect(injected(run)).toBe(publicAsk);
      // And it repeats, because nothing could record it — which is exactly why
      // it must not be the blocking form.
      const second = await runScript(stopHookScript(dataDir), stopInput);
      expect(injected(second)).toBe(publicAsk);
      expect(second.stdout).not.toContain('"decision":"block"');
    } finally {
      await chmod(dataDir, 0o700);
    }
  });

  it('takes an injected push-ledger row as the research signal too', async () => {
    await writeConfig({ hooks: { capture: 'block' } });
    await mkdir(dataDir, { recursive: true });
    await writeFile(
      join(dataDir, PUSH_LEDGER_FILE),
      `${JSON.stringify({ at: new Date().toISOString(), session: SESSION, trigger: 'prompt', action: 'injected' })}\n`,
    );
    const run = await runScript(stopHookScript(dataDir), stopInput);
    expect(JSON.parse(run.stdout)).toEqual({ decision: 'block', reason: publicAsk });
  });

  /**
   * The sidecar's own telemetry is not the session's research. The log-only read
   * arm fires on the first source file the agent opens and writes both a
   * push-hook search and a ledger row, which used to mean nearly every push-on
   * session ended in a block — including one that only read and edited code.
   */
  it('is not fooled by the sidecar looking things up on its own', async () => {
    await writeConfig({ hooks: { capture: 'block' } });
    await mkdir(dataDir, { recursive: true });
    await writeFile(
      join(dataDir, PUSH_LEDGER_FILE),
      [
        JSON.stringify({
          at: new Date().toISOString(),
          session: SESSION,
          trigger: 'read',
          action: 'logged',
        }),
        JSON.stringify({
          at: new Date().toISOString(),
          session: SESSION,
          trigger: 'prompt',
          action: 'skipped',
          reason: 'miss',
        }),
        '',
      ].join('\n'),
    );
    await writeFile(
      join(dataDir, 'searches.json'),
      JSON.stringify({
        schemaVersion: 1,
        searches: [
          {
            searchId: SEARCH_ID,
            at: new Date().toISOString(),
            question: 'zod gotcha bug workaround',
            decision: 'MISS',
            candidates: [],
            source: 'push-hook',
            sessionId: SESSION,
          },
        ],
      }),
    );
    const run = await runScript(stopHookScript(dataDir), stopInput);
    expect(run.stdout).toBe('');
  });

  it('says the same thing as context under nudge, and blocks nothing', async () => {
    await writeConfig({ hooks: { capture: 'nudge' } });
    await writeSearchSignal();
    const run = await runScript(stopHookScript(dataDir), stopInput);
    expect(run.stdout).not.toContain('"decision"');
    expect(injected(run)).toBe(publicAsk);
  });

  it('asks nothing of a session that did no research, or with capture off', async () => {
    await writeConfig({ hooks: { capture: 'block' } });
    const quiet = await runScript(stopHookScript(dataDir), stopInput);
    expect(quiet.stdout).toBe('');

    await writeConfig({});
    await writeSearchSignal();
    const off = await runScript(stopHookScript(dataDir), stopInput);
    expect(off.stdout).toBe('');
  });
});

