interface SeedSearch {
  searchId: string;
  question: string;
  decision: string;
  minutesAgo: number;
  resolved?: { by: string; at: string };
  /** A plain string, not {@link SearchSource}: one case deliberately seeds a
   *  source the CLI does not know, to pin that the Stop hook's default is
   *  silence rather than promotion into the strong arm. */
  source?: string;
  sessionId?: string;
}

async function seedSearches(entries: SeedSearch[]): Promise<void> {
  for (const e of entries) {
    await recordSearch(dataDir, {
      searchId: e.searchId,
      at: new Date(Date.now() - e.minutesAgo * 60_000).toISOString(),
      question: e.question,
      decision: e.decision,
      candidates: [],
      ...(e.resolved !== undefined
        ? { resolved: { by: e.resolved.by as SearchResolution, at: e.resolved.at } }
        : {}),
      ...(e.source !== undefined ? { source: e.source as SearchSource } : {}),
      ...(e.sessionId !== undefined ? { sessionId: e.sessionId } : {}),
    });
  }
}

/** Forget every recorded search, as `rm searches.json` used to. */
async function clearSearches(): Promise<void> {
  const store = await openStore(dataDir);
  store?.run('DELETE FROM searches', []);
  store?.close();
}

async function nagged(): Promise<string[]> {
  const raw = await readFile(join(dataDir, 'hook-nags.json'), 'utf8').catch(() => null);
  if (raw === null) return [];
  return Object.keys((JSON.parse(raw) as { nagged: Record<string, string> }).nagged);
}

/** The sessions that have already had their one weak batch. */
async function batchedSessions(): Promise<string[]> {
  const raw = await readFile(join(dataDir, 'hook-nags.json'), 'utf8').catch(() => null);
  if (raw === null) return [];
  const parsed = JSON.parse(raw) as { sessions?: Record<string, string> };
  return Object.keys(parsed.sessions ?? {});
}

/** Everything the Stop hook injected except the leading publish.mode line. */
function loopLines(run: HookRun): string[] {
  const text = injected(run) ?? '';
  if (text === '') return [];
  return text.split('\n').slice(1);
}

